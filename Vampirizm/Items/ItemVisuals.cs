using System.Collections.Generic;
using System.IO;
using Jotunn.Utils;
using UnityEngine;

namespace Vampirizm.Items
{
    // Shared helpers for embedded icons and world-model retexturing of cloned vanilla prefabs.
    internal static class ItemVisuals
    {
        private static readonly Dictionary<string, Texture2D> TextureCache = new Dictionary<string, Texture2D>();
        internal static Sprite LoadIcon(string icon)
        {
            string resource = "Vampirizm.Assets." + icon + ".png";
            using (Stream stream = typeof(ItemVisuals).Assembly.GetManifestResourceStream(resource))
            using (var buffer = new MemoryStream())
            {
                if (stream == null)
                {
                    Plugin.Warn("Icon resource is missing: " + resource);
                    return null;
                }
                stream.CopyTo(buffer);
                Texture2D texture = AssetUtils.LoadImage(buffer.ToArray());
                texture.name = icon;
                return Sprite.Create(texture, new Rect(0f, 0f, texture.width, texture.height), new Vector2(0.5f, 0.5f));
            }
        }

        // Swaps the main texture of every material whose current texture name matches a map entry
        // (embedded blood variants generated by Assets/generate_food_textures.py). New material
        // instances keep the vanilla prefab untouched. Falls back to a tint when nothing matched,
        // so a renamed vanilla texture degrades gracefully instead of leaving the item vanilla-looking.
        internal static void Retexture(GameObject prefab, Color fallbackTint, params KeyValuePair<string, string>[] maps)
        {
            bool matched = false;
            foreach (Renderer renderer in prefab.GetComponentsInChildren<Renderer>(true))
            {
                Material[] materials = renderer.sharedMaterials;
                for (int i = 0; i < materials.Length; i++)
                {
                    if (materials[i] == null || materials[i].mainTexture == null) continue;
                    string current = Normalize(materials[i].mainTexture.name);
                    foreach (KeyValuePair<string, string> map in maps)
                    {
                        if (current != Normalize(map.Key)) continue;
                        Texture2D replacement = LoadTexture(map.Value, materials[i].mainTexture);
                        if (replacement == null) continue;
                        var material = new Material(materials[i]) { mainTexture = replacement };
                        RehueColors(material);
                        materials[i] = material;
                        matched = true;
                        break;
                    }
                }
                renderer.sharedMaterials = materials;
            }
            if (!matched)
            {
                Plugin.Warn("No vanilla texture matched on " + prefab.name + "; using the tint fallback.");
                Tint(prefab, fallbackTint);
            }
        }

        private static string Normalize(string name) => name.Replace(" ", "").ToLowerInvariant();

        // Hue of the generated blood textures; matches generate_food_textures.py.
        private const float BloodHue = 0.985f;
        private static readonly string[] TintProperties = { "_Color", "_EmissionColor", "_MossColor" };

        // Some vanilla materials tint or light the texture (the royal jelly shell is multiplied by yellow-green and
        // glows yellow), which pulls a blood texture back to the vanilla look. Moving those colors to the blood hue
        // keeps their brightness, saturation and alpha; white and black colors are unaffected.
        private static void RehueColors(Material material)
        {
            foreach (string property in TintProperties)
            {
                if (!material.HasProperty(property)) continue;
                Color color = material.GetColor(property);
                Color.RGBToHSV(color, out float _, out float saturation, out float value);
                Color rehued = Color.HSVToRGB(BloodHue, saturation, value, true);
                rehued.a = color.a;
                material.SetColor(property, rehued);
            }
        }

        // Without a vanilla original the texture tiles with bilinear sampling.
        internal static Texture2D LoadTexture(string resource, Texture original = null)
        {
            if (TextureCache.TryGetValue(resource, out Texture2D cached)) return cached;
            string path = "Vampirizm.Assets." + resource + ".png";
            using (Stream stream = typeof(ItemVisuals).Assembly.GetManifestResourceStream(path))
            using (var buffer = new MemoryStream())
            {
                if (stream == null)
                {
                    Plugin.Warn("Texture resource is missing: " + path);
                    return null;
                }
                stream.CopyTo(buffer);
                Texture2D texture = AssetUtils.LoadImage(buffer.ToArray());
                texture.name = resource;
                // Keep the vanilla sampling so the swapped texture reads the same in the world.
                texture.filterMode = original != null ? original.filterMode : FilterMode.Bilinear;
                texture.wrapMode = original != null ? original.wrapMode : TextureWrapMode.Repeat;
                texture.anisoLevel = original != null ? original.anisoLevel : 4;
                TextureCache[resource] = texture;
                return texture;
            }
        }

        // New material instances so the vanilla prefab keeps its own look; a multiply keeps the texture shading.
        internal static void Tint(GameObject prefab, Color tint)
        {
            foreach (Renderer renderer in prefab.GetComponentsInChildren<Renderer>(true))
            {
                Material[] materials = renderer.sharedMaterials;
                for (int i = 0; i < materials.Length; i++)
                {
                    if (materials[i] == null) continue;
                    var material = new Material(materials[i]);
                    if (material.HasProperty("_Color")) material.color *= tint;
                    materials[i] = material;
                }
                renderer.sharedMaterials = materials;
            }
        }
    }
}
